"""Summarise the silver HTR experiment (scripts/silver_htr.py) into results/htr/silver/README.md."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'results/htr/silver'
sys.path.insert(0, str(ROOT / 'src'))
from htr import cer_interval, wer  # noqa: E402
FILES = dict(A='A', B='B', C='C', H='H', M='M', M1='M_run1_step2400')  # run key -> results file suffix
RUNS = [r for r in FILES if (OUT / f'val_metrics_{FILES[r]}.json').exists()]
NAMES = dict(A='A · human baseline', B='B · supplied silver', C='C · filtered teacher', H='H · human continuation',
             M='M · silver + human replay (exploratory)', M1='M run 1 · step 2400 (stalled before step 2800)')
SOURCES = ['all', 'silver sources', 'archive', 'dictation', 'school', 'university']
SILVER = ('archive', 'school', 'university')


def load(name):
    return json.loads((OUT / name).read_text(encoding='utf-8'))


def pick(df, source):
    if source == 'all':
        return df
    if source == 'silver sources':
        return df[df.source.isin(SILVER)]
    return df[df.source == source]


def paired(a, b, n=2000, seed=42):
    """Page-bootstrap 95% interval for CER(b) - CER(a) on the same lines."""
    pa = a.groupby('page_id')[['char_errors', 'chars']].sum()
    pb = b.groupby('page_id')[['char_errors']].sum().reindex(pa.index)
    ea, eb, ch = pa.char_errors.to_numpy(), pb.char_errors.to_numpy(), pa.chars.to_numpy()
    idx = np.random.default_rng(seed).integers(0, len(ch), (n, len(ch)))
    diff = (eb[idx].sum(1) - ea[idx].sum(1)) / ch[idx].sum(1)
    return (eb.sum() - ea.sum()) / ch.sum(), *np.percentile(diff, [2.5, 97.5])


def md(df):
    cols = list(df.columns)
    lines = ['| ' + ' | '.join(cols) + ' |', '| ' + ' | '.join('---' if c in ('run', 'source', 'comparison') else '---:'
                                                             for c in cols) + ' |']
    for row in df.itertuples(index=False):
        lines.append('| ' + ' | '.join(f'{v:.4f}' if isinstance(v, float) else f'{v:,}' if isinstance(v, (int, np.integer))
                                       else str(v) for v in row) + ' |')
    return '\n'.join(lines)


def main():
    text = ['# Silver fine-tuning of TrOCR (B/C)', '',
            'Generated by `scripts/silver_report.py` from the outputs of `scripts/run_silver_htr.sh`. '
            'All scores are on the original v2.2 human validation split (133 pages, 2,076 eligible lines). '
            'The v3.0 test set was not used.', '']

    teacher = load('teacher_filter.json')
    trains = {r: load(f'train_{r}.json') for r in 'BCHM' if (OUT / f'train_{r}.json').exists()}
    cfg = next(iter(trains.values()))['config'] if trains else None

    # --- line-level validation
    rows = []
    for r in RUNS:
        for x in load(f'val_metrics_{FILES[r]}.json')['results']:
            rows.append(dict(run=NAMES[r], source=x['source'], lines=x['lines'], CER=x['CER'],
                             CER_95=f"{x['CER_95_low']:.4f}–{x['CER_95_high']:.4f}", WER=x['WER']))
    for r in RUNS:
        g = pick(pd.read_csv(OUT / f'val_predictions_{FILES[r]}.csv', keep_default_na=False), 'silver sources')
        lo, hi = cer_interval(g)
        rows.append(dict(run=NAMES[r], source='silver sources', lines=len(g), CER=g.char_errors.sum() / g.chars.sum(),
                         CER_95=f'{lo:.4f}–{hi:.4f}', WER=wer(g.target, g.prediction)))
    val = pd.DataFrame(rows)
    val['order'] = val.source.map(SOURCES.index)
    text += ['## Line CER/WER on human validation (annotated crops, beam 4)', '',
             md(val.sort_values(['order', 'run']).drop(columns='order')), '',
             'Intervals are page-bootstrap 95% (1,000 resamples, seed 42).', '']

    preds = {r: pd.read_csv(OUT / f'val_predictions_{FILES[r]}.csv', keep_default_na=False) for r in RUNS}
    diffs = []
    for a, b in [('A', 'B'), ('A', 'C'), ('B', 'C'), ('A', 'H'), ('H', 'B'), ('H', 'C'), ('A', 'M'), ('B', 'M'), ('H', 'M'), ('A', 'M1'), ('H', 'M1')]:
        if a in preds and b in preds:
            for source in SOURCES:
                pa, pb = preds[a], preds[b]
                pa, pb = pick(pa, source), pick(pb, source)
                d, lo, hi = paired(pa, pb)
                diffs.append(dict(comparison=f'{b} − {a}', source=source, delta_CER=d, CI_95=f'{lo:+.4f} to {hi:+.4f}',
                                  significant='yes' if lo > 0 or hi < 0 else 'no'))
    if diffs:
        text += ['## Paired differences (same lines, page bootstrap)', '',
                 'Negative ΔCER means the second model is better. 2,000 paired page resamples.', '',
                 md(pd.DataFrame(diffs)), '']

    # --- page-level
    if (OUT / 'page_metrics.json').exists():
        pm = load('page_metrics.json')
        page = pd.DataFrame(pm['results'])
        page['CER_95'] = [f'{l:.4f}–{h:.4f}' for l, h in zip(page.CER_95_low, page.CER_95_high)]
        page['run'] = page.run.map(NAMES)
        page['order'] = page.source.map(SOURCES.index)
        text += [f"## Page CER with the midterm detector ({pm['detector']}, score ≥ {pm['score_threshold']})", '',
                 md(page.sort_values(['order', 'run'])[['run', 'source', 'pages', 'CER', 'CER_95']]), '',
                 'Missed lines count as deletions and extra predictions as insertions (as notebook 09).', '']
        pp = pd.read_csv(OUT / 'page_predictions.csv', keep_default_na=False)
        pdiffs = []
        for a, b in [('A', 'B'), ('A', 'C'), ('B', 'C'), ('A', 'M')]:
            if {a, b} <= set(pp.run):
                for source in SOURCES:
                    pa, pb = pp[pp.run == a], pp[pp.run == b]
                    pa, pb = pick(pa, source), pick(pb, source)
                    d, lo, hi = paired(pa, pb)
                    pdiffs.append(dict(comparison=f'{b} − {a}', source=source, delta_CER=d,
                                       CI_95=f'{lo:+.4f} to {hi:+.4f}', significant='yes' if lo > 0 or hi < 0 else 'no'))
        text += ['Paired page CER differences:', '', md(pd.DataFrame(pdiffs)), '']

    # --- training
    if trains:
        tr = []
        for r, t in trains.items():
            src = t['distinct_lines_by_source']
            tr.append(dict(run=NAMES[r], distinct_lines=t['training_lines'],
                           by_source=', '.join(f"{s} {v['lines']:,}" for s, v in src.items()),
                           pages=sum(v['pages'] for v in src.values()), optimizer_steps=t['optimizer_steps'],
                           passes=f"{t['optimizer_steps'] * cfg['batch_size'] / t['training_lines']:.2f}",
                           selected_step=t['selected_step'], minutes=f"{t['minutes']:.0f}",
                           sampler='resumable seeded permutations' if 'resumable' in t.get('sampler', '') else 'torch shuffle',
                           resumed_at=', '.join(map(str, t.get('resumed_at') or [])) or '–'))
        text += ['## Training runs', '', md(pd.DataFrame(tr)), '',
                 f"Shared settings: initialised from `{cfg['init']}` with a fresh AdamW (lr {cfg['lr']}, weight decay "
                 f"{cfg['weight_decay']}, linear schedule with {cfg['warmup_fraction']:.0%} warm-up), batch "
                 f"{cfg['batch_size']}, {cfg['steps']:,} optimizer steps, seed {cfg['seed']}, bf16 autocast, gradient "
                 f"checkpointing, targets ≤ {cfg['max_target_tokens']} tokens. Checkpoint selection: {cfg['selection']}. "
                 'Selection uses greedy decoding; reported scores use beam 4.', '']
        hist = []
        for r, t in trains.items():
            for h in t['history']:
                hist.append(dict(run=r, step=h['step'], train_loss=h['train_loss'] if h['train_loss'] is not None else '–',
                                 greedy_val_CER=h['val_CER'], greedy_val_WER=h['val_WER']))
        text += ['Greedy validation CER during training (step 0 is A):', '', md(pd.DataFrame(hist)), '']

    # --- teacher filter
    f = teacher['filter']
    acc_src = ', '.join(f"{s} {teacher['accepted_by_source'].get(s, 0):,}/{n:,}" for s, n in teacher['lines_by_source'].items())
    text += ['## C teacher labels and filter', '',
             f"Frozen A transcribed all {teacher['silver_lines']:,} silver crops (beam 4). Confidence is A's mean token "
             "log-probability of its own output, from a teacher-forced pass. The filter was fixed before C was "
             f"trained and never reads the supplied silver text: {f['min_chars']}–{f['max_chars']} characters, at least "
             f"one Cyrillic letter, no word repeated {f['max_word_repeat'] + 1}+ times in a row, and confidence ≥ τ. "
             f"τ = {teacher['tau']:.4f} is the lowest threshold at which A's accepted validation lines have CER ≤ "
             f"{f['target_val_cer']:.0%} ({teacher['calibration']['val_lines_accepted']:,} of "
             f"{teacher['calibration']['val_lines']:,} lines, CER {teacher['calibration']['val_accepted_CER']:.4f}).", '',
             f"- Accepted: **{teacher['accepted']:,} / {teacher['silver_lines']:,}** lines ({acc_src}); "
             f"{teacher['shape_rejected']:,} failed the shape checks.",
             f"- Agreement with the supplied silver transcripts (CER of teacher vs supplied): all "
             f"{teacher['teacher_vs_supplied_CER_all']:.4f}, accepted {teacher['teacher_vs_supplied_CER_accepted']:.4f}, "
             f"rejected {teacher['teacher_vs_supplied_CER_rejected']:.4f}; by source "
             + ', '.join(f'{s} {v:.4f}' for s, v in teacher['teacher_vs_supplied_CER_by_source'].items()) + '.',
             '']
    (OUT / 'README.md').write_text('\n'.join(text), encoding='utf-8')
    print('\n'.join(text))


if __name__ == '__main__':
    main()
